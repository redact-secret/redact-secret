/**
 * Runs the reference declarative ruleset fixture
 * (`conformance/fixtures/ruleset-reference.json`, issues #495, #1182, #1183)
 * against one surface, so the Node addon, the WebAssembly artifact and the
 * release CLI are held to the same accepted cases, the same default action and
 * the same rejection class as the Rust core and the Python binding, which have
 * their own consumers of the same file.
 *
 * A surface is described by three things, so this file carries no process,
 * environment or network access of its own:
 *
 * - `offsetUnit`: `"utf8-byte"` (the fixture's own unit, used by the CLI) or
 *   `"utf16"` (every JavaScript surface); expected ranges are converted with an
 *   independent reference conversion, never the binding under test.
 * - `scan(ruleset, input)`: the surface's findings for `input` under the
 *   ruleset (`ruleset` is a `Buffer`), each with `detector`, `type`,
 *   `confidence`, `action`, `start` and `end`.
 * - `reject(ruleset)`: the fixed rejection class name when the surface rejects
 *   the ruleset with `INVALID_RULESET`, or `undefined` when it loads it. A
 *   surface that cannot read the class (the public JavaScript package, by
 *   design) is not run through this file.
 *
 * Every ruleset text and input in the fixture is synthetic. The failures this
 * returns name a case id, a class and a count, never a ruleset or an input.
 */

import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const FIXTURE_PATH = join(REPO_ROOT, "conformance", "fixtures", "ruleset-reference.json");

/** The 18 public rejection classes, each exactly once in `rejections`. */
const CLASS_COUNT = 18;

export function loadRulesetReference() {
  const reference = JSON.parse(readFileSync(FIXTURE_PATH, "utf8"));
  if (reference.rejections.length !== CLASS_COUNT) {
    throw new Error(`ruleset-reference.json: expected ${CLASS_COUNT} rejections, found ${reference.rejections.length}`);
  }
  return reference;
}

/** UTF-8 byte offset to UTF-16 code-unit offset, independent of any binding. */
function utf16Offset(text, byteOffset) {
  return Buffer.from(text, "utf8").subarray(0, byteOffset).toString("utf8").length;
}

function convertOffset(unit, input, byteOffset) {
  return unit === "utf16" ? utf16Offset(input, byteOffset) : byteOffset;
}

/** The ruleset bytes of one rejection entry (some are generated by size). */
export function rejectionBytes(entry) {
  if (entry.oversizedBytes !== undefined) return Buffer.alloc(entry.oversizedBytes, "x");
  if (entry.detectorCount !== undefined) {
    let text = "ruleset-revision: 1\n";
    for (let index = 0; index < entry.detectorCount; index += 1) {
      text +=
        `detector: acme-token-${index}\nspecificity: contextual\nprefix: "ACME_"\n` +
        "alphabet: alnum-dash\nrun: at-least 20\nvalidator: none\n";
    }
    return Buffer.from(text, "utf8");
  }
  if (entry.nameCount !== undefined) {
    let text = "ruleset-revision: 1\nnames: ambiguous\n";
    for (let index = 0; index < entry.nameCount; index += 1) text += `name: corp-token-${index}\n`;
    return Buffer.from(text, "utf8");
  }
  return Buffer.from(entry.ruleset, "utf8");
}

function describeFinding(finding) {
  return [finding.detector, finding.type, finding.confidence, finding.action, finding.start, finding.end].join("|");
}

function expectedFinding(unit, input, expected) {
  return {
    detector: expected.detector,
    type: expected.type,
    confidence: expected.confidence,
    action: expected.action,
    start: convertOffset(unit, input, expected.start),
    end: convertOffset(unit, input, expected.end),
  };
}

function observedFinding(finding) {
  return {
    detector: finding.detector,
    type: finding.type,
    confidence: finding.confidence,
    action: finding.action,
    start: finding.start,
    end: finding.end,
  };
}

/**
 * Runs every accepted, names, ordering and rejection case of the fixture
 * through `surface`. Returns `{ checks, failures }`: the number of checks run
 * and one fixed-form string per disagreement.
 */
export function runRulesetReference(reference, surface) {
  const failures = [];
  let checks = 0;

  const expectFindings = (section, ruleset, cases) => {
    for (const testCase of cases) {
      checks += 1;
      const id = `${section}/${testCase.id}`;
      const findings = surface.scan(ruleset, testCase.input);
      if (testCase.findingCount === 0) {
        if (findings.length !== 0) failures.push(`${id}: expected no finding, got ${findings.length}`);
        continue;
      }
      const expected = expectedFinding(surface.offsetUnit, testCase.input, testCase);
      if (findings.length !== 1 || describeFinding(observedFinding(findings[0])) !== describeFinding(expected)) {
        failures.push(
          `${id}: expected ${describeFinding(expected)}, got [${findings.map((f) => describeFinding(observedFinding(f))).join(",")}]`,
        );
      }
    }
  };

  expectFindings("accepted", Buffer.from(reference.accepted.ruleset, "utf8"), reference.accepted.cases);
  expectFindings("names", Buffer.from(reference.names.ruleset, "utf8"), reference.names.cases);
  expectFindings("ordering", Buffer.from(reference.ordering.ruleset, "utf8"), [
    { ...reference.ordering.expectedWinner, id: reference.ordering.id, input: reference.ordering.input },
  ]);

  for (const [section, entries] of [
    ["rejections", reference.rejections],
    ["tightenedRejections", reference.tightenedRejections],
  ]) {
    for (const entry of entries) {
      checks += 1;
      const id = `${section}/${entry.id ?? entry.class}`;
      const actual = surface.reject(rejectionBytes(entry));
      if (actual !== entry.class)
        failures.push(`${id}: expected ${entry.class}, got ${actual ?? "an accepted ruleset"}`);
    }
  }

  return { checks, failures };
}
